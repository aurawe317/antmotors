-- =====================================================================
-- 照片墓碑（photo tombstones）—— 让「删除某张照片」永久生效
-- ---------------------------------------------------------------------
-- 背景：两台设备给同一辆车各加一张照片时，后上传的那次会把对方那张删掉。
-- 原因：服务端原先把「客户端列表里没出现的行」一律当成删除（全量替换），
--       于是「我这边不知道这张」被误读成了「我要删这张」。
--
-- 修法：
--   1) 服务端改成「并集合并」——只有显式墓碑（photoTombs）才会删除行；
--   2) 客户端删除照片时，按稳定 id（idx）记下墓碑并一起上传；
--   3) 墓碑存在 cars.photos_deleted 上，这样**别的设备**就算拿着删除前的
--      旧列表上传，也不会把已删除的照片"复活"。
--
-- 只要跑下面这一行 ALTER（幂等），第 3 点就生效；不跑也不影响 1、2 ——
-- 合并 + 当次删除照常工作，只是墓碑不再跨设备持久化（极少见的"复活"窗口）。
-- =====================================================================

alter table public.cars
  add column if not exists photos_deleted jsonb not null default '[]'::jsonb;

